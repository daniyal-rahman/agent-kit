#!/usr/bin/env python3
"""Install the kit for every coding agent on this machine. Safe to rerun.

  python3 install.py              install (or update after `git pull` in the kit)
  python3 install.py status       show what each agent tool loads
  python3 install.py --home DIR   use DIR as the home folder (for tests)

What it does:
- Writes ~/.agents/AGENTS.md = the kit's core.md + your ~/.agents/me.md + notes for
  this machine (~/.agents/machines/<hostname>.md). Every run rebuilds it: edit me.md,
  not AGENTS.md.
- Points each agent tool's instruction file at it: ~/.claude*/CLAUDE.md,
  ~/.codex/AGENTS.md, ~/.gemini/GEMINI.md, ~/.config/opencode/AGENTS.md (whichever
  tools are present). An existing file is copied to ~/.agents/backup/ first, and its
  text is added to me.md so nothing you wrote stops being loaded.
- Links the kit's skills into ~/.agents/skills (Codex and others read it) and into
  each ~/.claude*/skills. Your two personal skills (your tag word, your voice) are
  written from templates using ~/.agents/settings.json. A skill folder of your own
  with the same name is left alone, with a warning.
Nothing personal is written into the kit folder, so `git pull` there never conflicts.
"""
import datetime, json, os, re, shutil, socket, sys

KIT = os.path.dirname(os.path.abspath(__file__))
args = sys.argv[1:]
HOME = os.path.abspath(os.path.expanduser(args[args.index("--home") + 1])) if "--home" in args else os.path.expanduser("~")
AG = os.path.join(HOME, ".agents")
OUT = os.path.join(AG, "AGENTS.md")
STAMP = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
MARK = "Generated by agent-kit"

def settings():
    p = os.path.join(AG, "settings.json")
    return json.load(open(p)) if os.path.exists(p) else {}

def claude_homes():
    found = [os.path.join(HOME, n) for n in sorted(os.listdir(HOME)) if n == ".claude" or n.startswith(".claude-")]
    found = [p for p in found if os.path.isdir(p) and any(os.path.exists(os.path.join(p, f)) for f in ("settings.json", "projects", ".credentials.json", "CLAUDE.md"))]
    if not found and shutil.which("claude") and HOME == os.path.expanduser("~"):
        found = [os.path.join(HOME, ".claude")]
    return found

def instruction_files():
    files = [os.path.join(h, "CLAUDE.md") for h in claude_homes()]
    for d, f in ((".codex", "AGENTS.md"), (".gemini", "GEMINI.md"), (".config/opencode", "AGENTS.md")):
        if os.path.isdir(os.path.join(HOME, d)):
            files.append(os.path.join(HOME, d, f))
    return files

def backup(path):
    rel = os.path.relpath(path, HOME)
    dst = os.path.join(AG, "backup", STAMP, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.isdir(path) and not os.path.islink(path):
        shutil.copytree(path, dst, symlinks=True)
    else:
        shutil.copy2(path, dst, follow_symlinks=True) if os.path.exists(path) else open(dst, "w").write(os.readlink(path))
    return dst

def keep_old_text(path):
    """An instruction file the person already had: back it up and carry its text into me.md."""
    text = open(path, errors="replace").read().strip() if os.path.exists(path) else ""
    dst = backup(path)
    print(f"  backed up {path} -> {dst}")
    if not text or MARK in text:
        return
    me = os.path.join(AG, "me.md")
    old = open(me).read() if os.path.exists(me) else "# About the owner\n"
    if text in old:
        return
    open(me, "w").write(old.rstrip() + f"\n\n## Kept from {path.replace(HOME, '~')} ({STAMP[:8]})\n\n{text}\n")
    print(f"  carried its text into {me}")

def link(target, path):
    if os.path.islink(path) and os.readlink(path) == target:
        return
    if os.path.lexists(path):
        keep_old_text(path) if path.endswith(".md") else backup(path)
        os.remove(path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    os.symlink(target, path)
    print(f"  linked {path} -> {target}")

def generate():
    parts = [f"<!-- {MARK} from {KIT}/core.md + ~/.agents/me.md. Edit me.md, not this file. -->",
             open(os.path.join(KIT, "core.md")).read().strip()]
    s = settings()
    if s.get("owner"):
        parts.append(f"The owner is {s['owner']}." + (f" Their tag word is \"{s['tag']}\" (the `already-told-you` skill)." if s.get("tag") else ""))
    for p in (os.path.join(AG, "me.md"), os.path.join(AG, "machines", socket.gethostname().split(".")[0] + ".md")):
        if os.path.exists(p):
            parts.append(open(p).read().strip())
    text = "\n\n".join(parts) + "\n"
    os.makedirs(AG, exist_ok=True)
    if not os.path.exists(OUT) or open(OUT).read() != text:
        open(OUT + ".tmp", "w").write(text)
        os.replace(OUT + ".tmp", OUT)
        print(f"  wrote {OUT} ({text.count(chr(10))} lines)")

def render_personal(s):
    """Fill the tag and voice templates. Returns {name: folder} of rendered skills."""
    out = {}
    owner = s.get("owner") or "the owner"
    jobs = []
    if s.get("tag"):
        jobs.append(("already-told-you", "tag", {}))
    if os.path.isdir(os.path.join(AG, "voice", "library")):
        guide = open(os.path.join(KIT, "skills/voice-setup/candidate-voice.md")).read()
        guide = re.sub(r"^# .*\n+", "", guide).replace("the owner", owner)
        jobs.append(("voice", "voice", {"VOICE_GUIDE": guide.strip()}))
    for name, tpl, extra in jobs:
        text = open(os.path.join(KIT, "templates", tpl, "SKILL.md")).read()
        for k, v in dict(OWNER=owner, TAG=s.get("tag", ""), **extra).items():
            text = text.replace("{{" + k + "}}", v)
        d = os.path.join(AG, "skills", name)
        if os.path.islink(d):
            os.remove(d)
        os.makedirs(d, exist_ok=True)
        p = os.path.join(d, "SKILL.md")
        if not os.path.exists(p) or open(p).read() != text:
            open(p, "w").write(text)
            print(f"  wrote {p}")
        out[name] = d
    return out

def kit_skills():
    root = os.path.join(KIT, "skills")
    return {n: os.path.join(root, n) for n in sorted(os.listdir(root)) if os.path.exists(os.path.join(root, n, "SKILL.md"))}

def ours(target):
    return target.startswith(KIT + "/") or target.startswith(AG + "/skills/")

def install_skills(personal):
    shared = os.path.join(AG, "skills")
    os.makedirs(shared, exist_ok=True)
    wanted = kit_skills()
    for name, target in wanted.items():
        p = os.path.join(shared, name)
        if os.path.isdir(p) and not os.path.islink(p):
            print(f"  WARNING kept your own {p}; the kit's {name} is not installed there")
            continue
        link(target, p)
    names = set(wanted) | set(personal)
    for d in [os.path.join(h, "skills") for h in claude_homes()]:
        os.makedirs(d, exist_ok=True)
        for name in names:
            p = os.path.join(d, name)
            if os.path.isdir(p) and not os.path.islink(p):
                print(f"  WARNING kept your own {p}; the kit's {name} is not installed there")
                continue
            link(os.path.join(shared, name), p)
    for d in [shared] + [os.path.join(h, "skills") for h in claude_homes()]:
        for entry in os.listdir(d):
            p = os.path.join(d, entry)
            if os.path.islink(p) and entry not in names and ours(os.readlink(p)):
                os.remove(p)
                print(f"  removed old skill link {p}")

def install():
    print(f"agent-kit install into {HOME}")
    s = settings()
    generate()
    for f in instruction_files():
        link(OUT, f)
    sb = os.path.join(AG, "said-before.md")
    if not os.path.exists(sb):
        open(sb, "w").write("# What the owner has had to say before\n\nEmpty until setup mines it from past chats.\n")
    install_skills(render_personal(s))
    generate()  # me.md may have gained text from an old instruction file
    if not instruction_files():
        print("  no agent tool found (looked for ~/.claude*, ~/.codex, ~/.gemini, ~/.config/opencode)")
    print("done")

def status():
    print(f"{OUT}: {sum(1 for _ in open(OUT)) if os.path.exists(OUT) else 0} lines")
    for f in instruction_files():
        ok = os.path.islink(f) and os.path.realpath(f) == os.path.realpath(OUT)
        print(f"  {'ok ' if ok else 'OFF'} {f}")
    names = set(kit_skills()) | {n for n in ("already-told-you", "voice") if os.path.isdir(os.path.join(AG, "skills", n))}
    for d in [os.path.join(AG, "skills")] + [os.path.join(h, "skills") for h in claude_homes()]:
        missing = [n for n in sorted(names) if not os.path.exists(os.path.join(d, n, "SKILL.md"))]
        print(f"  {'ok ' if not missing else 'OFF'} {d}" + (f"  missing: {', '.join(missing)}" if missing else ""))

if __name__ == "__main__":
    status() if "status" in args else install()
